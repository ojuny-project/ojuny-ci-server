#!/usr/bin/env python3
"""Check that modules the installer rewrites do not own required wiring."""

from __future__ import annotations

import sys
from pathlib import Path

INSTALLER_HEADER = "# Generated by the Ojuny installer."


def read(root: Path, relative: str) -> str:
    return (root / relative).read_text(encoding="utf-8")


def main(argv: list[str]) -> int:
    root = Path(argv[1] if len(argv) > 1 else ".").resolve()
    failures: list[str] = []

    host_imports = read(root, "modules/default.nix")
    hardware = read(root, "modules/00-hardware.nix")
    user_module = read(root, "modules/00-user.nix")

    if "inputs.disko.nixosModules.disko" in host_imports:
        failures.append(
            "modules/default.nix imports the disko module; the installer rewrite cannot remove it"
        )

    if "../nixos/users.nix" not in host_imports:
        failures.append(
            "modules/default.nix does not import ../nixos/users.nix; the installer rewrite can drop the admin wiring"
        )

    if INSTALLER_HEADER not in hardware and "self.modules.nixos.disko" not in hardware:
        failures.append(
            "modules/00-hardware.nix must import self.modules.nixos.disko"
        )

    if INSTALLER_HEADER not in user_module and "../nixos/users.nix" in user_module:
        failures.append(
            "modules/00-user.nix imports ../nixos/users.nix; keep the admin wiring in host-imports"
        )

    if failures:
        print("\n".join(failures), file=sys.stderr)
        return 1

    print("installer-ownership: ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
